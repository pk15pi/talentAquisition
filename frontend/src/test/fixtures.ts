export function sessionUser(role: string, permissions: string[], extra: Partial<SessionUser> = {}): SessionUser {
  return {
    id: `${role}-id`,
    username: role.toLowerCase(),
    email: "",
    first_name: role,
    last_name: "User",
    employee_code: null,
    role,
    phone: "",
    is_active: true,
    is_superuser: false,
    permissions,
    can_own_client: permissions.includes("clients.own_client"),
    can_be_assigned_recruiter: permissions.includes("jobs.be_assigned_recruiter"),
    ...extra,
  };
}

export function page<T>(results: T[]) {
  return { data: { count: results.length, next: null, previous: null, results } };
}
